function PolicyBlock({ block }) {
  if (block.type === 'divider') {
    return <div className="my-10 h-px bg-[#0A3028]/10" />
  }

  if (block.type === 'heading') {
    const isMainSection = /^\d+\.\s/.test(block.text)
    const Tag = isMainSection ? 'h2' : block.level === 2 ? 'h3' : 'h4'
    const className =
      isMainSection
        ? 'scroll-mt-32 text-2xl font-extrabold leading-tight tracking-[-0.035em] text-[#071E1A] md:text-[2.15rem]'
        : block.level === 2
          ? 'scroll-mt-32 text-xl font-extrabold leading-tight tracking-[-0.025em] text-[#071E1A] md:text-2xl'
          : 'scroll-mt-32 text-lg font-extrabold leading-tight text-[#064537]'

    return (
      <Tag id={block.id} className={className}>
        {renderInline(block.text)}
      </Tag>
    )
  }

  if (block.type === 'list') {
    return (
      <ul className="grid gap-2.5 pl-5 text-base font-medium leading-8 text-[#4B5B55] marker:text-[#006B4D] md:text-[1.03rem]">
        {block.items.map((item, index) => (
          <li key={`${item}-${index}`} className="pl-1">
            {renderInline(item)}
          </li>
        ))}
      </ul>
    )
  }

  return (
    <p className="text-base font-medium leading-8 text-[#4B5B55] md:text-[1.03rem] md:leading-8">
      {renderInline(block.text)}
    </p>
  )
}

